import { z } from 'zod';
import { ALL_PROXY_KINDS, CLIENT_TARGETS } from '../../../shared/src/index.js';
import type { ClientTarget } from '../../../shared/src/index.js';
import { groupKinds } from '../services/ruleSchemeParser.js';

export const targetSchema = z.enum(Object.keys(CLIENT_TARGETS) as [ClientTarget, ...ClientTarget[]]);
export const modeSchema = z.enum(['fullConfiguration', 'nodesOnly']);
export const latencySchema = z.enum(['automatic', 'icmp', 'tcp']);
export const proxyKindSchema = z.enum(['unknown', ...ALL_PROXY_KINDS] as const);
export const text = z.string().min(1);
export const title = z.string().trim().min(1).max(256);
export const idSchema = z.string().min(1).max(128).refine(value => !['__proto__', 'constructor', 'prototype'].includes(value), 'Invalid identifier');
export const nameList = z.array(z.string()).max(10000);
const string = z.string().nullish();
const positive = z.number().int().nonnegative().nullish();
const boolean = z.boolean().nullish();
const optionalURL = z.string().url().nullish();
const plain = <T extends z.ZodTypeAny>(value: T) => z.record(idSchema, value);

export const requestOptionsSchema = z.object({
  userAgent: z.string().max(1024).regex(/^[\t\x20-\x7e\x80-\xff]*$/).nullish(),
  dnsOverHTTPSURL: optionalURL,
});

const usageSchema = z.object({ uploadBytes: positive, downloadBytes: positive, totalBytes: positive,
  expiresAt: string, notices: nameList.default([]) });
export const subscriptionSchema = z.object({
  id: idSchema, name: title, urlString: text, isEnabled: z.boolean(), createdAt: text,
  lastUpdatedAt: string, lastError: string, usage: usageSchema.nullish(),
  requestOptions: requestOptionsSchema.nullish(), nameWasAutoGenerated: boolean,
});
export const subscriptionPatchSchema = subscriptionSchema.pick({ name: true, urlString: true, isEnabled: true, requestOptions: true }).partial();

const shadowSchema = z.object({ version: z.number().int().min(1).max(3), host: text, password: text, skipCertificateVerification: z.boolean().optional() });
const masqueSchema = z.object({
  mode: z.enum(['keyConnectIP', 'basicConnectIP']), privateKey: string, publicKey: string, ipv4: string, ipv6: string,
  network: string, mtu: positive, dns: nameList.nullish(), remoteDNSResolve: boolean, httpVersion: positive,
  disableVersionFallback: boolean, headers: plain(z.string()).nullish(), certificate: nameList.nullish(),
});
const sshSchema = z.object({ privateKey: string, privateKeyPassphrase: string, hostKeys: nameList.default([]), hostKeyAlgorithms: nameList.default([]) });
const trustSchema = z.object({ quic: z.boolean(), clientRandomAuthKey: string });
export const nodeSchema = z.object({
  id: idSchema, sourceID: idSchema.nullish(), kind: proxyKindSchema, unrecognizedKind: string, name: text, server: text,
  port: z.number().int().min(1).max(65535), cipher: string, password: string, uuid: string, username: string,
  transport: string, transportMode: string, plugin: string, pluginMux: boolean, shadowTLS: shadowSchema.nullish(),
  masque: masqueSchema.nullish(), ssh: sshSchema.nullish(), trustTunnel: trustSchema.nullish(),
  tls: z.boolean().default(false), sni: string, hostHeader: string, path: string, alpn: string,
  realityPublicKey: string, realityShortID: string, realitySupportsX25519MLKEM768: boolean, certificateFingerprint: string,
  fingerprint: string, flow: string, vlessEncryption: string, skipCertificateVerification: z.boolean().default(false),
  alterID: positive, protocolName: string, protocolParam: string, obfs: string, obfsParam: string,
  idleSessionCheckInterval: positive, idleSessionTimeout: positive, minIdleSession: positive, version: positive,
  congestionControl: string, udpRelayMode: string, udpRelayEnabled: boolean, portHopping: string,
  upMbps: z.number().nonnegative().nullish(), downMbps: z.number().nonnegative().nullish(),
  wireGuardPrivateKey: string, wireGuardPublicKey: string, wireGuardPreSharedKey: string, wireGuardIPv4: string,
  wireGuardIPv6: string, wireGuardAllowedIPs: string, wireGuardReserved: string, wireGuardMTU: positive,
  wireGuardPersistentKeepalive: positive, wireGuardDNS: string, rawURI: z.string().default(''),
  isSubscriptionMetadata: boolean, countryOverride: string, hostsSourceServer: string,
});
export const nodePatchSchema = nodeSchema.omit({ id: true, sourceID: true, rawURI: true, isSubscriptionMetadata: true }).partial()
  .extend({ excluded: z.boolean().optional() });
export const nameFilterSchema = z.object({ includeKeywords: nameList, excludeKeywords: nameList, useRegex: z.boolean().optional() });
export const memberSchema = z.discriminatedUnion('type', [
  z.object({ type: z.literal('reference'), name: text }), z.object({ type: z.literal('nodePattern'), pattern: z.string().min(1).max(2048) }),
]);
export const groupKind = z.enum(groupKinds);
export const groupSchema = z.object({ name: title, kind: groupKind, members: z.array(memberSchema).max(10000).default([]),
  testURL: optionalURL, interval: positive, tolerance: positive, isCustomNodeFilter: boolean, iconEmoji: string, iconURL: optionalURL });
const network = z.object({ dnsServers: nameList.optional(), fallbackDNSServers: nameList.optional(),
  directDNSServers: nameList.optional(), skipProxyHosts: nameList.optional(), tunExcludedRoutes: nameList.optional(), ipv6: z.boolean().optional() });
const ruleResource = z.discriminatedUnion('type', [
  z.object({ type: z.literal('inline'), rule: text }), z.object({ type: z.literal('bundled'), file: text }),
  z.object({ type: z.literal('remote'), url: z.string().url().refine(value => new URL(value).protocol === 'https:') }),
]);
const ruleset = z.object({ groupName: title, resource: ruleResource, options: nameList.optional(),
  origin: z.enum(['source', 'supplement', 'added']).optional(), addedLabel: z.string().optional() });
export const schemeSchema = z.object({ id: idSchema, name: title, summary: z.string(), sourceURLString: optionalURL,
  rawConfigurationText: string, networkSettings: network.nullish(), groups: z.array(groupSchema), rulesets: z.array(ruleset),
  updatedAt: string, summaryIsUserEdited: boolean, isBundled: z.boolean() });
export const customizationSchema = z.object({
  groupOrder: nameList.optional(), matchingOrder: nameList.optional(), renamedGroups: plain(title).optional(), removedGroupNames: nameList.optional(),
  groupMemberOverrides: plain(z.array(memberSchema)).optional(), groupKindOverrides: plain(groupKind).optional(),
  addedNodeGroups: z.array(groupSchema).optional(), overridesNetworkSettings: z.boolean().optional(), networkSettingsOverride: network.nullish(),
});
export const flowSchema = z.object({
  id: idSchema, schemeID: idSchema, name: title, policyName: title, rulesText: z.string().default(''),
  isEnabled: z.boolean().default(true), localRuleSetID: idSchema.nullish(), catalogID: string, sourceURLString: optionalURL,
  generatedPolicyGroup: groupSchema.nullish(), isGroupSupplement: boolean,
});
export const localRuleSetSchema = z.object({ id: idSchema, name: title, rulesText: z.string(), sourceURLString: optionalURL });

export const tailnetSchema = z.object({
  id: idSchema, name: title, controlURLString: optionalURL, deviceName: string,
  subnets: nameList.default([]), magicDNSSuffix: string, isEnabled: z.boolean().default(true),
});
export const tailnetInputSchema = tailnetSchema.omit({ id: true }).extend({ authKey: z.string().max(4096).regex(/^[\w-]+$/).nullish() });
export const settingsSchema = z.object({
  configurationName: title, appendSubscriptionNameToNodes: z.boolean(), filterSubscriptionInfoNodes: z.boolean(),
  autoRefreshOnOpen: z.boolean(), preferRuleSets: z.boolean(), embedRemoteSubscriptionLinks: z.boolean(),
  latencyTestMode: latencySchema, dnsProtectionMode: z.enum(['standard', 'strict', 'followScheme']),
  theme: z.enum(['system', 'light', 'dark']),
});
export const exportPreferencesSchema = z.object({
  selectedTarget: targetSchema, visibleClientTargets: z.array(targetSchema), clientOrder: z.array(targetSchema),
  lanSharingOrderIndex: z.number().int().min(0).max(18), isLANSharingVisible: z.boolean(),
  exportContentModes: plain(modeSchema), excludedKinds: plain(z.array(proxyKindSchema)),
});
export const snapshotSchema = exportPreferencesSchema.extend({
  version: z.number().int().min(1),
  updatedAt: text,
  subscriptions: z.array(subscriptionSchema),
  nodes: z.array(nodeSchema),
  selectedPresetID: idSchema,
  importedSchemes: z.array(schemeSchema),
  selectedRuleGroups: plain(nameList),
  ruleSchemeCustomizations: plain(customizationSchema),
  ruleGroupEmojisEnabled: plain(z.boolean()),
  ruleGroupEmojiAutofill: plain(z.boolean()),
  excludedNodeIDs: nameList,
  nodeExportNameFilter: nameFilterSchema.nullish(),
  customRuleFlows: z.array(flowSchema),
  localRuleSets: z.array(localRuleSetSchema),
  tailnets: z.array(tailnetSchema),
  settings: settingsSchema,
});

export const unique = <T>(items: T[]) => [...new Set(items)];
